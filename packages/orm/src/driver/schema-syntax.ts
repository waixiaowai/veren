/**
 * 模式语法策略：列、主键、默认值和迁移账本的 DDL 由方言自己渲染。
 * Schema syntax strategy: the dialect renders column, primary-key, default and
 * migration-ledger DDL itself.
 *
 * @module @veren/orm/driver/schema-syntax
 */

import type { ColumnMetadata, EntityMetadata } from '../metadata/entity-metadata.ts'
import type { ColumnType } from '../types.ts'
import type { SqlDialect } from './dialect.ts'
import { dateOnly, formatMysqlDate } from './value-codec.ts'

/** DDL 渲染策略。 / DDL renderer. */
export interface SchemaSyntax {
  column(column: ColumnMetadata): string
  primaryKey(metadata: EntityMetadata): string | undefined
  autoIncrementPrimaryKey(): string
}

/** 标准 SQL 实现；方言只需覆盖差异。 / Standard SQL implementation; dialects override differences. */
export class BaseSchemaSyntax implements SchemaSyntax {
  constructor(protected readonly dialect: SqlDialect) {}

  column(column: ColumnMetadata): string {
    const name = this.dialect.escape(column.databaseName)
    const type = this.dialect.mapColumnType(column)
    if (column.isGenerated && column.type === 'integer') return `${name} ${type} GENERATED BY DEFAULT AS IDENTITY`
    const parts = [`${name} ${type}`]
    if (!column.isNullable) parts.push('NOT NULL')
    if (column.options.default !== undefined) parts.push(`DEFAULT ${this.defaultLiteral(column)}`)
    return parts.join(' ')
  }

  primaryKey(metadata: EntityMetadata): string | undefined {
    if (metadata.primaryColumns.length === 0) return undefined
    return `PRIMARY KEY (${metadata.primaryColumns.map((column) => this.dialect.escape(column.databaseName)).join(', ')})`
  }

  autoIncrementPrimaryKey(): string {
    return 'SERIAL PRIMARY KEY'
  }

  /** 默认值字面量；布尔用 SQL 标准 TRUE/FALSE。 / Default literal; booleans use SQL-standard TRUE/FALSE. */
  protected defaultLiteral(column: ColumnMetadata): string {
    return literal(column, (value) => value ? 'TRUE' : 'FALSE', baseDateLiteral)
  }
}

/** SQLite：自增列内联，单自增主键不再生成表级约束。 / SQLite: inline autoincrement, no table-level PK for a single generated key. */
export class SqliteSchemaSyntax extends BaseSchemaSyntax {
  override column(column: ColumnMetadata): string {
    if (column.isGenerated && column.type === 'integer') {
      return `${this.dialect.escape(column.databaseName)} INTEGER PRIMARY KEY AUTOINCREMENT`
    }
    return super.column(column)
  }

  override primaryKey(metadata: EntityMetadata): string | undefined {
    if (metadata.primaryColumns.length === 1 && metadata.primaryColumns[0]?.isGenerated) return undefined
    return super.primaryKey(metadata)
  }

  override autoIncrementPrimaryKey(): string {
    return 'INTEGER PRIMARY KEY AUTOINCREMENT'
  }

  protected override defaultLiteral(column: ColumnMetadata): string {
    return literal(column, (value) => value ? '1' : '0', baseDateLiteral)
  }
}

/** MySQL：自增列内联 `AUTO_INCREMENT`。 / MySQL: inline `AUTO_INCREMENT`. */
export class MysqlSchemaSyntax extends BaseSchemaSyntax {
  override column(column: ColumnMetadata): string {
    if (column.isGenerated && column.type === 'integer') {
      return `${this.dialect.escape(column.databaseName)} ${this.dialect.mapColumnType(column)} AUTO_INCREMENT`
    }
    return super.column(column)
  }

  override autoIncrementPrimaryKey(): string {
    return 'INT AUTO_INCREMENT PRIMARY KEY'
  }

  protected override defaultLiteral(column: ColumnMetadata): string {
    return literal(column, (value) => value ? '1' : '0', (value, type) => type === 'date' ? dateOnly(value) : formatMysqlDate(value))
  }
}

/** 默认值字面量：数字/布尔/日期/字符串/JSON。 / Default literal: number/boolean/date/string/JSON. */
function literal(
  column: ColumnMetadata,
  boolean: (value: boolean) => string,
  formatDate: (value: Date, type: ColumnType) => string,
): string {
  const value = column.options.default
  if (value === null) return 'NULL'
  if (typeof value === 'number' || typeof value === 'bigint') return String(value)
  if (typeof value === 'boolean') return boolean(value)
  if (value instanceof Date) return `'${formatDate(value, column.type)}'`
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`
  return `'${JSON.stringify(value).replaceAll("'", "''")}'`
}

/** 标准/ SQLite 日期默认值：date 只保留日历日，其余 ISO。 / Standard/SQLite date default: date keeps the calendar day, others ISO. */
function baseDateLiteral(value: Date, type: ColumnType): string {
  return type === 'date' ? dateOnly(value) : value.toISOString()
}
