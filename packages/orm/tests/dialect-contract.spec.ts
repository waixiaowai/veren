import { describe, expect, it } from 'vitest'
import {
  ColumnMetadata,
  EntityMetadata,
  MysqlDialect,
  PostgresDialect,
  SqliteDialect,
  UnsupportedCatalog,
  UnsupportedFeatureError,
} from '../src/index.ts'

/** 构造测试列。 / Build a test column. */
function column(type: string, options: object = {}, generated = false): ColumnMetadata {
  const metadata = new EntityMetadata({ targetName: 'T', tableName: 't' })
  return new ColumnMetadata(metadata, {
    propertyName: 'value',
    databaseName: 'value',
    type: type as never,
    options: { type: type as never, ...options },
    isPrimary: generated,
    isGenerated: generated,
  })
}

/** 三种内置方言的契约用例。 / Contract cases for the three built-in dialects. */
const cases = [
  { name: 'sqlite', dialect: new SqliteDialect(), boolean: 1, date: '2024-01-02', datetime: '2024-01-02T03:04:05.678Z', generated: 'INTEGER PRIMARY KEY AUTOINCREMENT', auto: 'INTEGER PRIMARY KEY AUTOINCREMENT', order: 'NULLS LAST' },
  { name: 'postgres', dialect: new PostgresDialect(), boolean: true, date: '2024-01-02', datetime: new Date('2024-01-02T03:04:05.678Z'), generated: 'GENERATED BY DEFAULT AS IDENTITY', auto: 'SERIAL PRIMARY KEY', order: 'NULLS LAST' },
  { name: 'mysql', dialect: new MysqlDialect(), boolean: 1, date: '2024-01-02', datetime: '2024-01-02 03:04:05.678', generated: 'AUTO_INCREMENT', auto: 'INT AUTO_INCREMENT PRIMARY KEY', order: 'IS NULL' },
] as const

describe.each(cases)('$name dialect contract', ({ dialect, boolean, date, datetime, generated, auto, order }) => {
  it('encodes values through the dialect codec', () => {
    expect(dialect.values.encode(column('boolean'), true)).toBe(boolean)
    expect(dialect.values.encode(column('date'), new Date('2024-01-02T03:04:05.678Z'))).toBe(date)
    expect(dialect.values.encode(column('datetime'), new Date('2024-01-02T03:04:05.678Z'))).toEqual(datetime)
    expect(dialect.values.decode(column('decimal'), '12.50')).toBe('12.5')
    expect(dialect.values.decode(column('bigint'), 123)).toBe('123')
    expect(dialect.values.decode(column('blob'), new Uint8Array([1, 2]))).toEqual(new Uint8Array([1, 2]))
  })

  it('renders ordering, paging and generated DDL', () => {
    expect(dialect.query.orderBy('"t"."value"', 'ASC')).toContain(order)
    expect(dialect.query.limitOffset(undefined, 2)).not.toBe('')
    expect(dialect.schema.column(column('integer', {}, true))).toContain(generated)
    expect(dialect.schema.autoIncrementPrimaryKey()).toBe(auto)
  })
})

describe('catalog contract', () => {
  it('fails loudly when a driver has no introspection', async () => {
    const catalog = new UnsupportedCatalog()
    await expect(catalog.listTables()).rejects.toBeInstanceOf(UnsupportedFeatureError)
    await expect(catalog.listColumns()).rejects.toBeInstanceOf(UnsupportedFeatureError)
  })
})
